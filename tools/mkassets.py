"""The firmware's fonts and masks as 4-bit Rust data: crates/ferrite-ui/src/assets.rs.

    python3 tools/mkassets.py          (needs Pillow with FreeType; output is committed)

Sources: fonts/*.ttf (OFL, licences beside them) and the shapes in tools/art.py (the logo is the same toroid as
assets/logo). Carried over from the rt950pro workspace's fw/tools/mkassets.py, Rust output only.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import art  # noqa: E402
from fontgen import Font  # noqa: E402

FONTS = os.path.join(HERE, "..", "fonts")
OUT = os.path.join(HERE, "..", "crates", "ferrite-ui", "src", "assets.rs")
DIG = " -.0123456789"
REG, BOLD = "JetBrainsMono-Regular.ttf", "JetBrainsMono-Bold.ttf"
NUM = "FerriteMonoTight-Bold.ttf"  # JetBrains Mono Bold, white space squeezed (tools/tighten.py)
WORD = "BarlowSemiCondensed-SemiBold.ttf"

FONT_LIST = [  # name, file, px, chars, tabular, latin1, use
    ("ui_12", REG, 12, None, False, True, "status bar, hints, labels"),
    ("ui_12b", BOLD, 12, None, False, True, "status bar emphasis, hint keys"),
    ("ui_15", REG, 15, None, False, True, "list rows, names"),
    ("ui_15b", BOLD, 15, None, False, True, "headings"),
    ("dig_46", NUM, 46, DIG, True, False, "slot A frequency"),
    ("dig_28", NUM, 28, DIG, True, False, "slot A last digits"),
    ("dig_26", NUM, 26, DIG, True, False, "slot B frequency"),
    ("dig_17", NUM, 17, DIG, True, False, "slot B last digits"),
    ("word_26", WORD, 26, " EFIRT", False, False, "FERRITE wordmark, boot list header"),
    ("word_40", WORD, 40, " EFIRT", False, False, "FERRITE wordmark, boot logo screen"),
]
MASK_LIST = [  # name, size, shape
    ("logo40_ring", 40, art.toroid_ring), ("logo40_wind", 40, art.toroid_wind),
    ("logo112_ring", 112, art.toroid_ring), ("logo112_wind", 112, art.toroid_wind),
    ("icon_check", 14, art.check), ("icon_dot", 14, art.dot), ("icon_cross", 14, art.cross),
    ("icon_lock", 14, art.lock), ("icon_gps", 12, art.gps), ("icon_bt", 11, art.bt),
]


def main():
    rs = ["// Generated by tools/mkassets.py. Do not edit.", "use crate::font4::{Font4, Glyph4, Mask4};", ""]
    total = 0
    for name, ttf, px, chars, tab, lat, use in FONT_LIST:
        f = Font(os.path.join(FONTS, ttf), px, chars, tab, lat)
        rs.append(f.rust_source(name))
        total += f.size_bytes()
    for name, size, shape in MASK_LIST:
        a = art.mask(size, shape)
        packed = bytes(a[i] << 4 | (a[i + 1] if i + 1 < len(a) else 0) for i in range(0, len(a), 2))
        rows = [", ".join(f"0x{b:02X}" for b in packed[i:i + 16]) + "," for i in range(0, len(packed), 16)]
        rs += [f"static {name.upper()}_BITS: [u8; {len(packed)}] = [", *("    " + r for r in rows), "];",
               f"pub static {name.upper()}: Mask4 = Mask4 {{ w: {size}, h: {size}, bits: &{name.upper()}_BITS }};", ""]
        total += len(packed)
    open(OUT, "w").write("\n".join(rs))
    print(f"{os.path.relpath(OUT)}: {len(FONT_LIST)} fonts, {len(MASK_LIST)} masks, about {total / 1024:.1f} KB of data")


if __name__ == "__main__":
    main()
