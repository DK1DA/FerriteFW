#!/usr/bin/env python3
"""4-bit anti-aliased proportional fonts for the firmware, and a renderer for proofs.

    python3 tools/fontgen.py c fonts/AtkinsonHyperlegible-Regular.ttf 12 ui_12 > ui_12.c
    python3 tools/fontgen.py c fonts/BarlowSemiCondensed-SemiBold.ttf 46 freq_46 --chars " -.0123456789" --tabular

Each glyph is rasterised by FreeType (through Pillow) at the pixel size given, cropped to its ink,
and stored at 4 bits per pixel (0 = background, 15 = full ink), two pixels per byte, rows top to
bottom. Metrics are relative to the pen position on the baseline. --tabular gives every digit the
widest digit's advance (centred), so frequencies do not shift as digits change.

The renderer (Canvas) blends those same 4-bit glyphs over a known background colour and rounds to
RGB565, as the firmware will, so proofs show what the panel gets. English only: ASCII by default,
Latin-1 with --latin1.
"""
import argparse
import sys

from PIL import Image, ImageDraw, ImageFont


class Font:
    def __init__(self, ttf, px, chars=None, tabular=False, latin1=False):
        self.ttf, self.px = ttf, px
        f = ImageFont.truetype(ttf, px, layout_engine=ImageFont.Layout.BASIC)
        self.ascent, self.descent = f.getmetrics()
        chars = chars or "".join(chr(c) for c in range(32, 127)) + (
            "".join(chr(c) for c in range(160, 256)) if latin1 else "")
        self.glyphs = {}
        for ch in chars:
            adv = int(round(f.getlength(ch)))
            box = f.getbbox(ch, anchor="ls")              # ink box, pen at (0, 0) on the baseline
            if box[2] <= box[0] or box[3] <= box[1]:
                self.glyphs[ch] = (adv, 0, 0, b"", 0, 0)
                continue
            w, h = box[2] - box[0], box[3] - box[1]
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=f, fill=255, anchor="ls")
            a = bytes((v * 15 + 127) // 255 for v in im.getdata())
            self.glyphs[ch] = (adv, box[0], box[1], a, w, h)
        if tabular:
            digits = [c for c in "0123456789" if c in self.glyphs]
            wide = max(self.glyphs[c][0] for c in digits)
            for c in digits:
                adv, x, y, a, w, h = self.glyphs[c]
                self.glyphs[c] = (wide, x + (wide - adv) // 2, y, a, w, h)

    def width(self, s):
        return sum(self.glyphs.get(c, self.glyphs.get("?", (0,)))[0] for c in s)

    def size_bytes(self, rle=None):
        return sum(7 + (len(rle(a, w, h)) if rle and w else (w * h + 1) // 2) for _, _, _, a, w, h in self.glyphs.values())

    def c_source(self, name, header=True):
        chars = sorted(self.glyphs, key=ord)
        first, last = ord(chars[0]), ord(chars[-1])
        bits, recs = bytearray(), []
        for code in range(first, last + 1):
            g = self.glyphs.get(chr(code))
            if not g:
                recs.append(f"    {{ 0, 0, 0, 0, 0, 0 }}, /* missing {code} */")
                continue
            adv, x, y, a, w, h = g
            off = len(bits)
            for i in range(0, len(a), 2):
                bits.append(a[i] << 4 | (a[i + 1] if i + 1 < len(a) else 0))
            recs.append(f"    {{ {off}, {w}, {h}, {x}, {y}, {adv} }}, /* {chr(code)!r} */")
        lines = [",".join(f"0x{b:02X}" for b in bits[i:i + 16]) + "," for i in range(0, len(bits), 16)]
        head = [f"/* Generated by tools/fontgen.py from {self.ttf.split('/')[-1]}, {self.px} px. Do not edit. */",
                '#include "font4.h"', ""] if header else [f"/* {name}: {self.ttf.split('/')[-1]}, {self.px} px */"]
        return "\n".join([
            *head,
            f"static const uint8_t {name}_bits[] = {{", *("    " + l for l in lines), "};", "",
            f"static const glyph4_t {name}_glyphs[] = {{", *recs, "};", "",
            f"const font4_t {name} = {{ {self.ascent + self.descent}, {self.ascent}, {first}, {last - first + 1}, "
            f"{name}_glyphs, {name}_bits }};", ""])


    def tables(self):
        """(first, records, bits): records are (off, w, h, x, y, adv) per code from first, gaps as zeros."""
        chars = sorted(self.glyphs, key=ord)
        first, last = ord(chars[0]), ord(chars[-1])
        bits, recs = bytearray(), []
        for code in range(first, last + 1):
            g = self.glyphs.get(chr(code))
            if not g:
                recs.append((0, 0, 0, 0, 0, 0))
                continue
            adv, x, y, a, w, h = g
            off = len(bits)
            for i in range(0, len(a), 2):
                bits.append(a[i] << 4 | (a[i + 1] if i + 1 < len(a) else 0))
            recs.append((off, w, h, x, y, adv))
        return first, recs, bytes(bits)

    def rust_source(self, name, section=None, rle=None):
        """Rust statics: the sorted code points, a glyph record per code point, the 4-bit pixels.
        `section`: a linker section for the data on the radio (host builds ignore it). `rle`: an encoder
        (mkassets.rle) to store each glyph run-length encoded, its rows decoded in turn (font4.rs)."""
        codes = sorted(self.glyphs, key=ord)
        bits, recs = bytearray(), []
        for ch in codes:
            adv, x, y, a, w, h = self.glyphs[ch]
            off = len(bits)
            if rle:
                if w:
                    bits += rle(a, w, h)
            else:
                for i in range(0, len(a), 2):
                    bits.append(a[i] << 4 | (a[i + 1] if i + 1 < len(a) else 0))
            recs.append((off, w, h, x, y, adv))
        assert not rle or max(r[1] for r in recs) <= 64, f"{name}: run-length glyphs must be at most 64 px wide"
        assert len(bits) < 65536, f"{name}: glyph offsets must fit u16"
        assert max(ord(c) for c in codes) < 65536, f"{name}: code points must fit u16"
        up = name.upper()
        attr = [f'#[cfg_attr(target_os = "none", link_section = "{section}")]'] if section else []
        rows = [", ".join(f"0x{b:02X}" for b in bits[i:i + 16]) + "," for i in range(0, len(bits), 16)]
        g = [f"    Glyph4 {{ off: {o}, w: {w}, h: {h}, x: {x}, y: {y}, adv: {a} }}, // {ch!r}"
             for (o, w, h, x, y, a), ch in zip(recs, codes)]
        cp = [", ".join(f"0x{ord(c):02X}" for c in codes[i:i + 16]) + "," for i in range(0, len(codes), 16)]
        return "\n".join([f"// {name}: {self.ttf.split('/')[-1]}, {self.px} px, {len(codes)} characters"
                          + (", run-length encoded" if rle else ""),
                          *attr, f"static {up}_BITS: [u8; {len(bits)}] = [", *("    " + r for r in rows), "];",
                          *attr, f"static {up}_GLYPHS: [Glyph4; {len(recs)}] = [", *g, "];",
                          *attr, f"static {up}_CODES: [u16; {len(codes)}] = [", *("    " + r for r in cp), "];",
                          f"pub static {up}: Font4 = Font4 {{ line_h: {self.ascent + self.descent}, ascent: {self.ascent}, "
                          f"rle: {str(bool(rle)).lower()}, codes: &{up}_CODES, glyphs: &{up}_GLYPHS, bits: &{up}_BITS }};", ""])


def rgb565(c):
    r, g, b = c
    return ((r >> 3) * 255 // 31, (g >> 2) * 255 // 63, (b >> 3) * 255 // 31)


def hexc(s):
    return tuple(int(s[i:i + 2], 16) for i in (1, 3, 5))


class Canvas:
    """A 240 x 320 portrait panel. Colours are '#RRGGBB'; everything lands as RGB565."""
    def __init__(self, w=240, h=320, bg="#0B0D10"):
        self.im = Image.new("RGB", (w, h), rgb565(hexc(bg)))
        self.d = ImageDraw.Draw(self.im)

    def fill(self, x, y, w, h, c):
        self.d.rectangle([x, y, x + w - 1, y + h - 1], fill=rgb565(hexc(c)))

    def frame(self, x, y, w, h, c, r=0, width=1):
        self.d.rounded_rectangle([x, y, x + w - 1, y + h - 1], radius=r, outline=rgb565(hexc(c)), width=width)

    def panel(self, x, y, w, h, fill, edge, r=4):
        self.d.rounded_rectangle([x, y, x + w - 1, y + h - 1], radius=r, fill=rgb565(hexc(fill)),
                                 outline=rgb565(hexc(edge)))

    def mask(self, x, y, a, w, h, fg):
        f = hexc(fg)
        for j in range(h):
            for i in range(w):
                v = a[j * w + i]
                if v and 0 <= x + i < self.im.width and 0 <= y + j < self.im.height:
                    b = self.im.getpixel((x + i, y + j))
                    self.im.putpixel((x + i, y + j), rgb565(tuple(b[k] + (f[k] - b[k]) * v // 15 for k in range(3))))

    def text(self, x, base, s, font, fg="#F0F3F6", align="left"):
        if align == "right":
            x -= font.width(s)
        elif align == "center":
            x -= font.width(s) // 2
        for ch in s:
            adv, gx, gy, a, w, h = font.glyphs.get(ch, font.glyphs.get("?"))
            if w:
                self.mask(x + gx, base + gy, a, w, h, fg)
            x += adv
        return x

    def icon(self, x, y, size, draw_fn, fg):
        """Icons are 4-bit masks too (tools/art.py)."""
        from art import mask
        self.mask(x, y, mask(size, draw_fn), size, size, fg)

    def zoom(self, k=3):
        return self.im.resize((self.im.width * k, self.im.height * k), Image.NEAREST)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("c", help="C source on stdout")
    p.add_argument("ttf"); p.add_argument("px", type=int); p.add_argument("name")
    p.add_argument("--chars"); p.add_argument("--tabular", action="store_true"); p.add_argument("--latin1", action="store_true")
    a = ap.parse_args()
    f = Font(a.ttf, a.px, a.chars, a.tabular, a.latin1)
    sys.stdout.write(f.c_source(a.name))
    print(f"{a.name}: {len(f.glyphs)} glyphs, {f.size_bytes()} bytes", file=sys.stderr)


if __name__ == "__main__":
    main()
