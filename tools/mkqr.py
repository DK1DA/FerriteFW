#!/usr/bin/env python3
"""The manual's QR code for About's Help pages (HELP-2): crates/ferrite-ui/src/qr.rs.

    python3 tools/mkqr.py          (needs segno: pip install segno; output is committed)

MANUAL_URL below is the one place the address lives: the Rust file carries it as text and as the QR matrix, one
u32 per row (bit 28 - x is module x, 1 = dark), placed with the fonts in slow flash. Nothing is encoded at run time.
"""
import os
import segno

# Placeholder until the own domain is chosen (decision 98): change it here and run this again.
MANUAL_URL = "https://ferrite.example/manual"

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "ferrite-ui", "src", "qr.rs")


def main():
    q = segno.make(MANUAL_URL, error="m", micro=False, boost_error=True)
    rows = [[bool(v) for v in row] for row in q.matrix]
    n = len(rows)
    assert n <= 32, "a row must fit a u32: keep the address short"
    words = []
    for row in rows:
        w = 0
        for x, dark in enumerate(row):
            if dark:
                w |= 1 << (n - 1 - x)
        words.append(w)
    rs = [
        "//! Generated by tools/mkqr.py from its MANUAL_URL; do not edit. The manual's address and its QR code (HELP-2).",
        "",
        "/// The online manual (placeholder until the own domain is chosen: decision 98).",
        f'pub const MANUAL_URL: &str = "{MANUAL_URL}";',
        "",
        f"/// QR version {q.version}, error level {q.error}: {n} x {n} modules, no quiet zone.",
        f"pub const QR_SIZE: i32 = {n};",
        "",
        "/// One word per row, bit (QR_SIZE - 1 - x) set for a dark module at column x.",
        '#[cfg_attr(target_os = "none", link_section = ".slow_rodata")]',
        f"pub static MANUAL_QR: [u32; {n}] = [",
    ]
    rs += [f"    0x{w:08X}," for w in words]
    rs += ["];", ""]
    open(OUT, "w").write("\n".join(rs))
    print(f"{os.path.relpath(OUT)}: {MANUAL_URL} -> version {q.version}-{q.error}, {n} x {n}")


if __name__ == "__main__":
    main()
