#!/usr/bin/env python3
"""THIRD-PARTY-LICENSES.md: the notices for what other people wrote that ends up in the firmware image.

    python3 tools/thirdparty.py           # writes THIRD-PARTY-LICENSES.md at the repo root
    python3 tools/thirdparty.py --check   # exit 1 if the file is stale (CI, before a release)

What counts: the crates the firmware links for its target (cargo metadata, thumbv7em-none-eabihf, normal
dependencies of `ferrite`), less proc-macro crates and what only they pull in (they run at build time and leave
nothing in the image), less our own workspace crates; the Rust standard library's core and compiler_builtins; and the fonts drawn into the image (fonts/OFL-*.txt).
Crates offered under several licences are taken under MIT where it is one of them. Each crate's own licence
file is quoted (its copyright line matters); a crate that ships none gets the standard text with its authors.
Standard library only.
"""
import json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD-PARTY-LICENSES.md")
TARGET = "thumbv7em-none-eabihf"
FONTS = [  # (name, use, licence file): fonts rasterised into the image (tools/fontgen.py, tools/mkassets.py)
    ("JetBrains Mono", "the interface text; Ferrite Mono Tight, the digits, is derived from it", "fonts/OFL-JetBrainsMono.txt"),
    ("Barlow Semi Condensed", "the FERRITE wordmark", "fonts/OFL-BarlowSemiCondensed.txt"),
]
MIT_TEXT = """Permission is hereby granted, free of charge, to any person obtaining a copy of this software and associated
documentation files (the "Software"), to deal in the Software without restriction, including without limitation the
rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the Software, and to permit
persons to whom the Software is furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all copies or substantial portions of the
Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE
WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR
COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR
OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE."""


def crates():
    m = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--filter-platform", TARGET,
         "--manifest-path", os.path.join(ROOT, "firmware/Cargo.toml")],
        check=True, capture_output=True, text=True).stdout)
    pk = {p["id"]: p for p in m["packages"]}
    nodes = {n["id"]: n for n in m["resolve"]["nodes"]}
    root = next(p["id"] for p in m["packages"] if p["name"] == "ferrite" and p["source"] is None)
    seen, stack = set(), [root]
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        if any("proc-macro" in t["kind"] for t in pk[i]["targets"]):
            continue  # build time only: nothing of it is linked
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    return sorted((pk[i] for i in seen if pk[i]["source"] is not None), key=lambda p: (p["name"], p["version"]))


def chosen(expr):
    """The licence we take a crate under: MIT where offered, else the expression as given."""
    words = expr.replace("/", " OR ").replace("(", " ").replace(")", " ").split()
    if "MIT" in words and " AND " not in expr:
        return "MIT"
    return expr


def licence_text(p, lic):
    d = os.path.dirname(p["manifest_path"])
    names = sorted(os.listdir(d))
    pick = [n for n in names if n.upper().startswith(("LICENSE-MIT", "LICENCE-MIT"))] if lic == "MIT" else []
    pick = pick or [n for n in names if n.upper().startswith(("LICENSE", "LICENCE", "COPYING", "UNLICENSE"))
                    and "APACHE" not in n.upper()]
    if pick:
        return "\n\n".join(open(os.path.join(d, n), encoding="utf-8", errors="replace").read().strip() for n in pick)
    if lic == "MIT":
        return "MIT License\n\nCopyright (c) " + ", ".join(p["authors"] or ["the " + p["name"] + " authors"]) + "\n\n" + MIT_TEXT
    raise SystemExit(f"{p['name']} {p['version']}: no licence file and not MIT ({lic}): add it by hand")


def render():
    out = ["# Third-party licences", "",
           "Ferrite's firmware image includes the work of others, listed here with their licences. Ferrite itself is",
           "under the PolyForm Noncommercial licence (LICENSE.md). Generated by `tools/thirdparty.py`; don't edit.", "",
           "## Rust crates", "", "| Crate | Version | Licence | Taken under |", "|---|---|---|---|"]
    cs = crates()
    for p in cs:
        out.append(f"| {p['name']} | {p['version']} | {p['license']} | {chosen(p['license'])} |")
    out.append("| Rust standard library (core, compiler_builtins) | the toolchain's | MIT OR Apache-2.0 | MIT |")
    out += ["", "## Fonts", ""]
    for name, use, _ in FONTS:
        out.append(f"- {name} (SIL Open Font License 1.1): {use}.")
    out += ["", "## Licence texts", ""]
    for p in cs:
        out += [f"### {p['name']} {p['version']}", "", "```", licence_text(p, chosen(p["license"])), "```", ""]
    out += ["### Rust standard library (core, compiler_builtins)", "", "```",
            "MIT License\n\nCopyright (c) The Rust Project Developers\n\n" + MIT_TEXT, "```", ""]
    for name, _, f in FONTS:
        out += [f"### {name}", "", "```", open(os.path.join(ROOT, f), encoding="utf-8").read().strip(), "```", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if old != text:
            sys.exit("THIRD-PARTY-LICENSES.md is stale: run python3 tools/thirdparty.py")
        print("THIRD-PARTY-LICENSES.md: current")
    else:
        open(OUT, "w", encoding="utf-8").write(text)
        print(f"wrote {OUT}")
