#!/usr/bin/env python3
"""Link compression (LINK-51, decisions 285 and 286): the reference codec, byte for byte ferrite_core::linkz.

LZSS over a window of what one direction of a session has carried, kept across frames: a flag byte before every 8
tokens (bit 0 first), 1 a match (two bytes little endian: the offset back less 1 in the low log2(W) bits, the
length less 3 above), 0 a literal. The encoder keeps only the newest position for each of 512 hashes. Radio to PC
(DOWN) has a 1 KB window, PC to radio (UP) 512 bytes. Both ends must see the same frames in order: a frame sent plain
goes into the window too (`seen`); any error, retry or new session starts both over.

    python3 tools/linkz.py score CORPUS.pkl          # bytes per traffic type (a corpus: frame payloads by type)
    python3 tools/linkz.py emit CORPUS.pkl           # crates/ferrite-core/src/linkz_data.rs and linkz_vectors.rs
"""
import os, pickle, sys

DOWN, UP, HEADS, MIN = 1024, 512, 512, 3


def _hash(a, b, c):
    return (a << 6 ^ b << 3 ^ c) & (HEADS - 1)


class Lz:
    """One direction's window (W bytes): `encode` keeps the heads, `decode` only the window."""

    def __init__(self, w=DOWN):
        self.w, self.bits = w, w.bit_length() - 1
        self.max = MIN + (1 << (16 - self.bits)) - 1
        self.reset()

    def reset(self):
        self.win, self.n, self.heads = bytearray(self.w), 0, [0] * HEADS

    def _at(self, p):
        return self.win[p % self.w]

    def _push(self, b):
        self.win[self.n % self.w] = b
        self.n += 1
        if self.n >= 3:
            p = self.n - 3
            self.heads[_hash(self._at(p), self._at(p + 1), self._at(p + 2))] = (p & 0xFFFF) + 1

    def seen(self, data):
        for b in data:
            self._push(b)

    def encode(self, data):
        out, i, bit, flags_at = bytearray(), 0, 8, 0
        while i < len(data):
            if bit == 8:
                flags_at, bit = len(out), 0
                out.append(0)
            best = (0, 0)
            if len(data) - i >= MIN:
                link = self.heads[_hash(data[i], data[i + 1], data[i + 2])]
                if link:
                    low = (link - 1) & 0xFFFF
                    p = self.n - ((self.n - low) & 0xFFFF)
                    off = self.n - p
                    if 0 < off <= self.w:
                        ln = 0
                        while ln < self.max and i + ln < len(data):
                            src = self._at(p + ln) if ln < off else data[i + ln - off]
                            if src != data[i + ln]:
                                break
                            ln += 1
                        best = (ln, off)
            if best[0] >= MIN:
                v = (best[1] - 1) | (best[0] - MIN) << self.bits
                out += bytes([v & 0xFF, v >> 8])
                out[flags_at] |= 1 << bit
                for k in range(best[0]):
                    self._push(data[i + k])
                i += best[0]
            else:
                out.append(data[i])
                self._push(data[i])
                i += 1
            bit += 1
        return bytes(out)

    def decode(self, data):
        out, i = bytearray(), 0
        while i < len(data):
            flags = data[i]
            i += 1
            for bit in range(8):
                if i >= len(data):
                    break
                if flags >> bit & 1:
                    v = data[i] | data[i + 1] << 8
                    i += 2
                    off, ln = (v & (self.w - 1)) + 1, (v >> self.bits) + MIN
                    if off > self.n:
                        raise ValueError("a match before the start")
                    for _ in range(ln):
                        b = self._at(self.n - off)
                        out.append(b)
                        self.win[self.n % self.w] = b
                        self.n += 1
                else:
                    out.append(data[i])
                    self.win[self.n % self.w] = data[i]
                    self.n += 1
                    i += 1
        return bytes(out)


def score(corpus):
    print(f"{'traffic':<12}{'frames':>7}{'plain':>8}{'coded':>8}  ratio")
    for k, frames in corpus.items():
        w = UP if k.endswith("_write") else DOWN
        e, d = Lz(w), Lz(w)
        plain = coded = 0
        for f in frames:
            c = e.encode(f)
            if len(c) < len(f):
                assert d.decode(c) == f
                coded += len(c)
            else:
                d.seen(f)
                coded += len(f)
            plain += len(f)
        print(f"{k:<12}{len(frames):>7}{plain:>8}{coded:>8}  {coded / plain:.2f}")


def emit(corpus, root):
    samples = corpus["ui"][:4] + corpus["liveview"][:2] + corpus["daily_read"][:2]
    src = ["//! Generated by `tools/linkz.py emit` from a link traffic corpus (a simulator session, clear's daily channel",
           "//! set). Rebuild with the tool; never edit by hand.", "",
           "/// Sample frames for the bench (`bt linkz`) and the tests: UI pages, Live View deltas, channel answers.",
           '#[cfg(any(test, feature = "bench"))]', "pub static SAMPLES: &[&[u8]] = &["]
    src += [f"    &[{', '.join(map(str, f))}]," for f in samples] + ["];"]
    open(os.path.join(root, "linkz_data.rs"), "w").write("\n".join(src) + "\n")
    e = Lz(DOWN)
    vec = ["//! Test vectors from tools/linkz.py: the reference's DOWN encodings of SAMPLES, in order, one session.",
           "pub static VECTORS: &[&[u8]] = &["]
    vec += [f"    &[{', '.join(map(str, e.encode(f)))}]," for f in samples] + ["];"]
    open(os.path.join(root, "linkz_vectors.rs"), "w").write("\n".join(vec) + "\n")


if __name__ == "__main__":
    cmd, path = sys.argv[1], sys.argv[2]
    corpus = pickle.load(open(path, "rb"))
    if cmd == "score":
        score(corpus)
    elif cmd == "emit":
        emit(corpus, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "ferrite-core", "src"))
