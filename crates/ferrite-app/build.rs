//! Compiles the terminal's page templates (`src/term/pages.vt`) into the template pack: the bytes `term::tpl` reads,
//! in the format the SPI flash would hold them (decision 342; the format is described in `src/term/tpl.rs`), and
//! the names' numbers for the firmware's side. Only with the `vt100` feature. On the radio the pack is an SPI part
//! (decision 335): the static is in host builds only (the packer writes it out, tests read it).
//!
//! It also builds the text pack (decision 335, UPD-22): every `txt!("...")` and `txtc!("...")` literal in `src/`
//! (and the terminal's `no!(t, "...")`, which goes through `txt!`)
//! gets a number, the pack's body (`text_en.bin`, the SPI part's body) holds the texts, and the two macros map each
//! literal to its number, so the text itself never reaches the MCU's flash.

use std::collections::HashMap;
use std::fmt::Write as _;

fn main() {
    println!("cargo:rerun-if-changed=src/term/pages.vt");
    println!("cargo:rerun-if-changed=build.rs");
    texts();
    if std::env::var_os("CARGO_FEATURE_VT100").is_none() {
        return;
    }
    let src = std::fs::read_to_string("src/term/pages.vt").expect("src/term/pages.vt");
    let (pack, ids) = compile(&src).unwrap_or_else(|e| panic!("pages.vt: {e}"));
    let mut rs = String::new();
    rs.push_str("// Generated by build.rs from src/term/pages.vt.\n");
    for (k, v) in &ids {
        writeln!(rs, "pub const {k}: u8 = {v};").unwrap();
    }
    // host builds only: on the radio the pack is an SPI part (decision 335, UPD-21), read by `tpl::load`
    assert!(pack.len() <= 4096, "the template pack is {} bytes: tpl::PACK_MAX is 4096", pack.len());
    rs.push_str("#[cfg(not(target_os = \"none\"))]\n");
    writeln!(rs, "pub static PACK: [u8; {}] = {:?};", pack.len(), pack).unwrap();
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out.join("vt_pack.rs"), rs).unwrap();
    std::fs::write(out.join("vt_pack.bin"), &pack).unwrap();
}

/// Words, strings kept whole (their escapes undone).
#[derive(Debug, Clone, PartialEq)]
enum T {
    W(String),
    Str(Vec<u8>),
}

fn tokens(line: &str) -> Result<Vec<T>, String> {
    let b = line.as_bytes();
    let (mut v, mut i) = (Vec::new(), 0);
    while i < b.len() {
        match b[i] {
            b' ' | b'\t' => i += 1,
            b';' => {
                v.push(T::W(";".into()));
                i += 1;
            }
            b'"' => {
                let mut s = Vec::new();
                i += 1;
                loop {
                    let c = *b.get(i).ok_or("no closing quote")?;
                    i += 1;
                    match c {
                        b'"' => break,
                        b'\\' => {
                            let e = *b.get(i).ok_or("escape at the end")?;
                            i += 1;
                            match e {
                                b'n' => s.push(b'\n'),
                                b'"' => s.push(b'"'),
                                b'\\' => s.push(b'\\'),
                                b'x' => {
                                    let h = std::str::from_utf8(&b[i..i + 2]).map_err(|e| e.to_string())?;
                                    s.push(u8::from_str_radix(h, 16).map_err(|e| e.to_string())?);
                                    i += 2;
                                }
                                _ => return Err(format!("unknown escape \\{}", e as char)),
                            }
                        }
                        _ => s.push(c),
                    }
                }
                v.push(T::Str(s));
            }
            _ => {
                let st = i;
                while i < b.len() && !matches!(b[i], b' ' | b'\t' | b';' | b'"') {
                    i += 1;
                }
                v.push(T::W(line[st..i].into()));
            }
        }
    }
    Ok(v)
}

const KINDS: [(&str, &str); 7] = [("srcs", "SRC"), ("conds", "COND"), ("counts", "COUNT"), ("pickns", "PICKN"), ("ctxs", "CTX"), ("acts", "ACT"), ("pages", "PAGE")];

struct Asm {
    names: HashMap<String, HashMap<String, u8>>,
    /// The strings, deduplicated: their offsets are filled in when the pack is laid out.
    strings: Vec<Vec<u8>>,
}

impl Asm {
    fn id(&self, kind: &str, name: &str) -> Result<u8, String> {
        self.names[kind].get(name).copied().ok_or_else(|| format!("no {kind} named {name}"))
    }

    fn string(&mut self, s: Vec<u8>) -> u16 {
        match self.strings.iter().position(|x| *x == s) {
            Some(i) => i as u16,
            None => {
                self.strings.push(s);
                (self.strings.len() - 1) as u16
            }
        }
    }
}

const KEYS: [(&str, u8); 11] = [("up", 0x80), ("down", 0x81), ("left", 0x82), ("right", 0x83), ("pgup", 0x84), ("pgdn", 0x85), ("home", 0x86), ("end", 0x87), ("enter", 0x88), ("esc", 0x89), ("digit", 0x8A)];

/// A page as assembled: string indices (offsets later), the rules' bytes, the keys (string indices for `cmd`).
struct Page {
    hints: u16,
    help: u16,
    rules: Vec<u8>,
    keys: Vec<(u8, u8, u16, bool)>,
}

fn word(t: &[T], i: usize) -> Result<&str, String> {
    match t.get(i) {
        Some(T::W(w)) => Ok(w),
        x => Err(format!("a word expected, got {x:?}")),
    }
}

fn text(t: &[T], i: usize) -> Result<Vec<u8>, String> {
    match t.get(i) {
        Some(T::Str(s)) => Ok(s.clone()),
        x => Err(format!("a string expected, got {x:?}")),
    }
}

fn num(t: &[T], i: usize) -> Result<u8, String> {
    word(t, i)?.parse().map_err(|e| format!("{e}"))
}

fn ops(a: &Asm, t: &[T]) -> Result<Vec<u8>, String> {
    let mut o = Vec::new();
    let mut depth = 0i32;
    for op in t.split(|x| *x == T::W(";".into())).filter(|x| !x.is_empty()) {
        let short = |o: &mut Vec<u8>, code: u8, s: &[u8]| -> Result<(), String> {
            o.push(code);
            o.push(u8::try_from(s.len()).map_err(|_| "a string over 255 bytes in a row")?);
            o.extend_from_slice(s);
            Ok(())
        };
        match word(op, 0)? {
            "s" => short(&mut o, 0x10, &text(op, 1)?)?,
            "bold" => {
                o.push(0x13);
                short(&mut o, 0x10, &text(op, 1)?)?;
                o.push(0x15);
            }
            "at" => o.extend([0x11, num(op, 1)?]),
            "src" => o.extend([0x12, a.id("srcs", word(op, 1)?)?]),
            "bon" => o.push(0x13),
            "won" => o.push(0x14),
            "back" => o.push(0x15),
            "sel" => o.push(0x16),
            "selfill" => o.push(0x17),
            "fill" => o.push(0x18),
            "plain" => o.push(0x19),
            "digit" => o.push(0x1A),
            "pick" => short(&mut o, 0x1B, &text(op, 1)?)?,
            "pickn" => {
                let s = text(op, 2)?;
                o.extend([0x1C, a.id("pickns", word(op, 1)?)?, u8::try_from(s.len()).map_err(|_| "a string over 255 bytes in a row")?]);
                o.extend(s);
            }
            "ctx" => o.extend([0x1D, a.id("ctxs", word(op, 1)?)?]),
            "if" => {
                o.extend([0x20, a.id("conds", word(op, 1)?)?]);
                depth += 1;
            }
            "ifnot" => {
                o.extend([0x21, a.id("conds", word(op, 1)?)?]);
                depth += 1;
            }
            "ifi" => {
                o.extend([0x22, num(op, 1)?]);
                depth += 1;
            }
            "else" => o.push(0x23),
            "fi" => {
                o.push(0x24);
                depth -= 1;
            }
            "ret" => o.push(0x25),
            w => return Err(format!("unknown op {w}")),
        }
    }
    if depth != 0 {
        return Err("if without fi".into());
    }
    Ok(o)
}

/// The pack, and every name's number for the firmware.
type Compiled = (Vec<u8>, Vec<(String, u8)>);

fn compile(src: &str) -> Result<Compiled, String> {
    let mut a = Asm { names: HashMap::new(), strings: Vec::new() };
    let mut ids = Vec::new();
    let mut pages: Vec<Page> = Vec::new();
    let mut globals: Vec<(String, u16)> = Vec::new();
    for (n, line) in src.lines().enumerate() {
        let at = |e: String| format!("line {}: {e}", n + 1);
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let t = tokens(line).map_err(at)?;
        let head = word(&t, 0).map_err(at)?;
        if let Some((k, pre)) = KINDS.iter().find(|(k, _)| *k == head) {
            let mut m = HashMap::new();
            for (i, x) in t[1..].iter().enumerate() {
                let T::W(w) = x else { return Err(at("names only".into())) };
                m.insert(w.clone(), i as u8);
                ids.push((format!("{pre}_{}", w.to_uppercase()), i as u8));
            }
            a.names.insert(k.to_string(), m);
            continue;
        }
        match head {
            "string" => {
                let s = text(&t, 2).map_err(at)?;
                let i = a.string(s);
                globals.push((word(&t, 1).map_err(at)?.into(), i));
            }
            "page" => {
                let want = a.id("pages", word(&t, 1).map_err(at)?).map_err(at)?;
                if want as usize != pages.len() {
                    return Err(at("pages in the order `pages` lists them".into()));
                }
                pages.push(Page { hints: 0, help: 0, rules: Vec::new(), keys: Vec::new() });
            }
            "hints" | "help" => {
                let i = a.string(text(&t, 1).map_err(at)?);
                let p = pages.last_mut().ok_or_else(|| at("outside a page".into()))?;
                if head == "hints" {
                    p.hints = i
                } else {
                    p.help = i
                }
            }
            "row" | "bot" | "list" | "tail" => {
                let (kind, x, y, from) = match head {
                    "row" => (1, num(&t, 1).map_err(at)?, 0, 2),
                    "bot" => (2, num(&t, 1).map_err(at)?, 0, 2),
                    "list" => (3, num(&t, 1).map_err(at)?, a.id("counts", word(&t, 2).map_err(at)?).map_err(at)?, 3),
                    _ => (4, num(&t, 1).map_err(at)?, 0, 2),
                };
                if word(&t, from - 1).map_err(at)? == ";" {
                    return Err(at("rule header too short".into()));
                }
                let body = ops(&a, &t[from..]).map_err(at)?;
                let len = u8::try_from(body.len()).map_err(|_| at("a rule over 255 bytes".into()))?;
                let p = pages.last_mut().ok_or_else(|| at("outside a page".into()))?;
                p.rules.extend([kind, x, y, len]);
                p.rules.extend(body);
            }
            "key" => {
                let k = match &t[1] {
                    T::Str(s) if s.len() == 1 => s[0].to_ascii_lowercase(),
                    T::W(w) => KEYS.iter().find(|(n, _)| n == w).map(|x| x.1).ok_or_else(|| at(format!("no key {w}")))?,
                    _ => return Err(at("a key".into())),
                };
                let act = word(&t, 2).map_err(at)?;
                let id = a.id("acts", act).map_err(at)?;
                let (arg, is_str) = match act {
                    "go" => (a.id("pages", word(&t, 3).map_err(at)?).map_err(at)? as u16, false),
                    "cmd" => (a.string(text(&t, 3).map_err(at)?), true),
                    _ => (0, false),
                };
                pages.last_mut().ok_or_else(|| at("outside a page".into()))?.keys.push((k, id, arg, is_str));
            }
            w => return Err(at(format!("unknown statement {w}"))),
        }
    }
    // Layout: header, global string offsets, page offsets, pages (head, rules, keys), strings.
    let np = pages.len();
    let head = 6 + 2 * globals.len() + 2 * np;
    let page_len = |p: &Page| 6 + p.rules.len() + 1 + 4 * p.keys.len() + 1;
    let strings_at = head + pages.iter().map(page_len).sum::<usize>();
    let mut soff = Vec::new();
    let mut at = strings_at;
    for s in &a.strings {
        soff.push(u16::try_from(at).map_err(|_| "the pack is over 64 KB")?);
        at += 2 + s.len();
    }
    let mut o = Vec::new();
    o.extend(b"FVT\x01");
    o.push(np as u8);
    o.push(globals.len() as u8);
    for (name, i) in &globals {
        ids.push((format!("STR_{}", name.to_uppercase()), (o.len() - 6) as u8 / 2));
        o.extend(soff[*i as usize].to_le_bytes());
    }
    let mut p_at = head;
    for p in &pages {
        o.extend((p_at as u16).to_le_bytes());
        p_at += page_len(p);
    }
    for p in &pages {
        let start = o.len();
        o.extend(soff[p.hints as usize].to_le_bytes());
        o.extend(soff[p.help as usize].to_le_bytes());
        let keys_at = start + 6 + p.rules.len() + 1;
        o.extend((keys_at as u16).to_le_bytes());
        o.extend(&p.rules);
        o.push(0);
        for &(k, id, arg, is_str) in &p.keys {
            o.extend([k, id]);
            o.extend(if is_str { soff[arg as usize] } else { arg }.to_le_bytes());
        }
        o.push(0);
    }
    assert_eq!(o.len(), strings_at);
    for s in &a.strings {
        o.extend((s.len() as u16).to_le_bytes());
        o.extend(s);
    }
    Ok((o, ids))
}

// ---- the text pack ----

/// A `txt!`/`txtc!` literal: its source text between the quotes (what the macro arm matches) and its value.
struct Lit {
    raw: String,
    value: Vec<u8>,
}

/// The string literal starting at `b[i]` (a `"`): its raw text and value, and where it ends.
fn literal(b: &[u8], i: usize) -> Result<(Lit, usize), String> {
    let mut j = i + 1;
    let mut v = Vec::new();
    while j < b.len() && b[j] != b'"' {
        if b[j] == b'\\' {
            j += 1;
            match b[j] {
                b'n' => v.push(b'\n'),
                b't' => v.push(b'\t'),
                b'r' => v.push(b'\r'),
                b'0' => v.push(0),
                b'\\' | b'"' | b'\'' => v.push(b[j]),
                b'x' => {
                    v.push(u8::from_str_radix(std::str::from_utf8(&b[j + 1..j + 3]).unwrap(), 16).map_err(|e| e.to_string())?);
                    j += 2;
                }
                b'u' => {
                    let end = j + b[j..].iter().position(|&c| c == b'}').ok_or("no } in \\u{}")?;
                    let h = std::str::from_utf8(&b[j + 2..end]).unwrap();
                    let c = char::from_u32(u32::from_str_radix(h, 16).map_err(|e| e.to_string())?).ok_or("bad \\u")?;
                    let mut t = [0u8; 4];
                    v.extend_from_slice(c.encode_utf8(&mut t).as_bytes());
                    j = end;
                }
                b'\n' => {
                    while j + 1 < b.len() && b[j + 1].is_ascii_whitespace() {
                        j += 1;
                    }
                }
                c => return Err(format!("unknown escape \\{}", c as char)),
            }
            j += 1;
        } else {
            v.push(b[j]);
            j += 1;
        }
    }
    if j >= b.len() {
        return Err("no closing quote".into());
    }
    Ok((Lit { raw: String::from_utf8(b[i + 1..j].to_vec()).unwrap(), value: v }, j + 1))
}

fn rs_files(dir: &std::path::Path, out: &mut Vec<std::path::PathBuf>) {
    let mut v: Vec<_> = std::fs::read_dir(dir).unwrap().map(|e| e.unwrap().path()).collect();
    v.sort();
    for p in v {
        if p.is_dir() {
            rs_files(&p, out);
        } else if p.extension().is_some_and(|e| e == "rs") {
            out.push(p);
        }
    }
}

/// The text pack: every literal of `txt!(` and `txtc!(` in `src/`, in file order, each once.
fn texts() {
    println!("cargo:rerun-if-changed=src");
    let mut files = Vec::new();
    rs_files(std::path::Path::new("src"), &mut files);
    let mut lits: Vec<Lit> = Vec::new();
    for f in &files {
        let src = std::fs::read_to_string(f).unwrap();
        let b = src.as_bytes();
        let mut i = 0;
        // The terminal's refusals, `no!(t, "...", ...)` (term/cmd.rs), go through `txt!` too.
        let mut k = 0;
        while let Some(p) = src[k..].find("no!(") {
            let at = k + p;
            k = at + 4;
            let line_start = src[..at].rfind('\n').map_or(0, |n| n + 1);
            if src[line_start..at].contains("//") || at > 0 && (b[at - 1].is_ascii_alphanumeric() || b[at - 1] == b'_') {
                continue;
            }
            // the first argument (an expression without quotes), a comma, then the literal
            let Some(q) = src[k..].find(['"', ')', ';']) else { continue };
            if b[k + q] != b'"' || !src[k..k + q].contains(',') {
                continue;
            }
            let (lit, _) = literal(b, k + q).unwrap_or_else(|e| panic!("{}: {e}", f.display()));
            if lit.value.len() > 255 {
                panic!("{}: a text of {} bytes (255 at most: split it): {}", f.display(), lit.value.len(), lit.raw);
            }
            if !lits.iter().any(|l| l.raw == lit.raw) {
                lits.push(lit);
            }
        }
        while let Some(p) = src[i..].find("txt") {
            let at = i + p;
            i = at + 3;
            let rest = &src[at..];
            let skip = if rest.starts_with("txt!(") {
                5
            } else if rest.starts_with("txtc!(") {
                6
            } else {
                continue;
            };
            // not in a comment, nor part of a longer name
            let line_start = src[..at].rfind('\n').map_or(0, |n| n + 1);
            if src[line_start..at].contains("//") || at > 0 && (b[at - 1].is_ascii_alphanumeric() || b[at - 1] == b'_') {
                continue;
            }
            let mut j = at + skip;
            while b[j].is_ascii_whitespace() {
                j += 1;
            }
            if b[j] != b'"' {
                continue; // the macro's own definition (`$t`)
            }
            let (lit, end) = literal(b, j).unwrap_or_else(|e| panic!("{}: {e}", f.display()));
            if lit.value.len() > 255 {
                panic!("{}: a text of {} bytes (255 at most: split it): {}", f.display(), lit.value.len(), lit.raw);
            }
            if !lits.iter().any(|l| l.raw == lit.raw) {
                lits.push(lit);
            }
            i = end;
        }
    }
    assert!(lits.len() < 31 << 6, "too many texts for txtc!'s two characters");
    // The body: count u16, 0 u16, an entry per text (offset from the body's start, length in the top 8 bits), texts.
    let n = lits.len();
    let mut body = Vec::new();
    body.extend_from_slice(&(n as u16).to_le_bytes());
    body.extend_from_slice(&[0, 0]);
    let mut at = 4 + 4 * n;
    for l in &lits {
        body.extend_from_slice(&((at as u32) | (l.value.len() as u32) << 24).to_le_bytes());
        at += l.value.len();
    }
    for l in &lits {
        body.extend_from_slice(&l.value);
    }
    let mut rs = String::from("// Generated by build.rs from the txt!/txtc! literals in src/ (the text pack).\n");
    rs.push_str("/// A text in the text pack, by its literal: its number (UPD-22).\n#[allow(unused_macros)]\nmacro_rules! txt {\n");
    for (k, l) in lits.iter().enumerate() {
        writeln!(rs, "    (\"{}\") => {{ $crate::text::Txt({k}) }};", l.raw).unwrap();
    }
    rs.push_str("    ($t:tt) => { compile_error!(\"txt!: a string literal\") };\n");
    rs.push_str("}\n/// A text's number as two characters, for a table string (`concat!`): `text::code`.\n#[allow(unused_macros)]\nmacro_rules! txtc {\n");
    for (k, l) in lits.iter().enumerate() {
        // a control character, then one of 0x20-0x5F: never a `|`, so a table string's fields still split
        writeln!(rs, "    (\"{}\") => {{ \"\\u{{{:x}}}\\u{{{:x}}}\" }};", l.raw, 1 + (k >> 6), 0x20 + (k & 0x3F)).unwrap();
    }
    rs.push_str("    ($t:tt) => { compile_error!(\"txtc!: a string literal\") };\n}\n");
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out.join("txt_macros.rs"), rs).unwrap();
    std::fs::write(out.join("text_en.bin"), body).unwrap();
}
