//! Compiles the terminal's pages (`src/term/pages.vt`, a small stack language) into the template pack: the program
//! `term::tpl` runs (decision 346; the language is described in `pages.vt`, the byte format in `src/term/tpl.rs`),
//! and the names' numbers for the firmware's side. Only with the `vt100` feature. On the radio the pack is an SPI
//! part (decision 335): the static is in host builds only (the packer writes it out, tests read it).
//!
//! It also builds the text pack (decision 335, UPD-22): every `txt!("...")` and `txtc!("...")` literal in `src/`
//! (and the terminal's `no!(t, "...")`, which goes through `txt!`)
//! gets a number, the pack's body (`text_en.bin`, the SPI part's body) holds the texts, and the two macros map each
//! literal to its number, so the text itself never reaches the MCU's flash.

use std::collections::HashMap;
use std::fmt::Write as _;

fn main() {
    println!("cargo:rerun-if-changed=src/term/pages.vt");
    println!("cargo:rerun-if-changed=build.rs");
    texts();
    if std::env::var_os("CARGO_FEATURE_VT100").is_none() {
        return;
    }
    let src = std::fs::read_to_string("src/term/pages.vt").expect("src/term/pages.vt");
    let (pack, ids) = compile(&src).unwrap_or_else(|e| panic!("pages.vt: {e}"));
    let mut rs = String::new();
    rs.push_str("// Generated by build.rs from src/term/pages.vt.\n");
    for (k, ty, v) in &ids {
        if *ty == "fn" {
            writeln!(rs, "{v}").unwrap();
        } else {
            writeln!(rs, "pub const {k}: {ty} = {v};").unwrap();
        }
    }
    // host builds only: on the radio the pack is an SPI part (decision 335, UPD-21), read by `tpl::load`
    rs.push_str("#[cfg(not(target_os = \"none\"))]\n");
    writeln!(rs, "pub static PACK: [u8; {}] = {:?};", pack.len(), pack).unwrap();
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out.join("vt_pack.rs"), rs).unwrap();
    std::fs::write(out.join("vt_pack.bin"), &pack).unwrap();
}

/// The opcodes (`term/tpl.rs` matches on these names).
const OPS: [&str; 34] = [
    "RET", "LIT8", "LIT16", "JMP", "JZ", "CALL", "DUP", "DROP", "SWAP", "OVER", "ADD", "SUB", "MUL", "DIV", "MOD", "EQ", "LT", "GT",
    "AND", "OR", "NOT", "MIN", "MAX", "GET", "SET", "AGET", "ASET", "STR", "RAW", "AT", "NUM", "NUMW", "PCALL", "NAT",
];

fn op(name: &str) -> u8 {
    OPS.iter().position(|o| *o == name).unwrap() as u8
}

/// The words that are one opcode.
const SIMPLE: [(&str, &str); 22] = [
    ("exit", "RET"), ("dup", "DUP"), ("drop", "DROP"), ("swap", "SWAP"), ("over", "OVER"), ("+", "ADD"), ("-", "SUB"), ("*", "MUL"),
    ("/", "DIV"), ("mod", "MOD"), ("=", "EQ"), ("<", "LT"), (">", "GT"), ("and", "AND"), ("or", "OR"), ("not", "NOT"), ("min", "MIN"),
    ("max", "MAX"), ("aget", "AGET"), ("aset", "ASET"), ("at", "AT"), (".", "NUM"),
];
/// A page's entries, in its jump table (PCALL's byte), and what the lib calls them.
const PAGE_ENTRIES: [&str; 6] = ["draw", "key", "hints", "help", "prep", "poll"];
/// The lib's entries, in its jump table: what the firmware calls.
const LIB_ENTRIES: [&str; 4] = ["frame", "key", "prep", "poll"];

const KEYS: [(&str, i32); 13] = [
    ("up", 0x80), ("down", 0x81), ("left", 0x82), ("right", 0x83), ("pgup", 0x84), ("pgdn", 0x85), ("home", 0x86), ("end", 0x87),
    ("enter", 0x88), ("esc", 0x89), ("bs", 0x8B), ("line", 0xA0), ("lesc", 0xA1),
];

/// Words, strings kept whole (their escapes undone).
#[derive(Debug, Clone, PartialEq)]
enum T {
    W(String),
    Str(Vec<u8>),
}

/// A line's tokens: `\` (alone) starts a comment to the end of the line.
fn tokens(line: &str) -> Result<Vec<T>, String> {
    let b = line.as_bytes();
    let (mut v, mut i) = (Vec::new(), 0);
    while i < b.len() {
        match b[i] {
            b' ' | b'\t' => i += 1,
            b'\\' if b.get(i + 1).is_none_or(|c| *c == b' ') => break,
            b'"' => {
                let mut s = Vec::new();
                i += 1;
                loop {
                    let c = *b.get(i).ok_or("no closing quote")?;
                    i += 1;
                    match c {
                        b'"' => break,
                        b'\\' => {
                            let e = *b.get(i).ok_or("escape at the end")?;
                            i += 1;
                            match e {
                                b'n' => s.push(b'\n'),
                                b'"' => s.push(b'"'),
                                b'\\' => s.push(b'\\'),
                                b'x' => {
                                    let h = std::str::from_utf8(&b[i..i + 2]).map_err(|e| e.to_string())?;
                                    s.push(u8::from_str_radix(h, 16).map_err(|e| e.to_string())?);
                                    i += 2;
                                }
                                _ => return Err(format!("unknown escape \\{}", e as char)),
                            }
                        }
                        _ => s.push(c),
                    }
                }
                v.push(T::Str(s));
            }
            _ => {
                let st = i;
                while i < b.len() && !matches!(b[i], b' ' | b'\t' | b'"') {
                    i += 1;
                }
                v.push(T::W(line[st..i].into()));
            }
        }
    }
    // `( ... )` is a comment (a word's stack effect)
    let mut out = Vec::new();
    let mut skip = false;
    for x in v {
        match &x {
            T::W(w) if w == "(" && !skip => skip = true,
            T::W(w) if skip && w.ends_with(')') => skip = false,
            _ if skip => {}
            _ => out.push(x),
        }
    }
    Ok(out)
}

/// Where code goes: its bytes from address `base`, the calls to words not placed yet, and its open
/// `if`/`begin`s.
struct Seg {
    code: Vec<u8>,
    base: usize,
    calls: Vec<(usize, String)>,
    ctl: Vec<(char, usize)>,
}

impl Seg {
    fn here(&self) -> usize {
        self.base + self.code.len()
    }

    fn op(&mut self, o: &str) {
        self.code.push(op(o));
    }

    fn op_a(&mut self, o: &str, a: usize) {
        self.op(o);
        self.code.extend((a as u16).to_le_bytes());
    }

    fn patch(&mut self, at: usize, a: usize) {
        let i = at - self.base;
        self.code[i..i + 2].copy_from_slice(&(a as u16).to_le_bytes());
    }

    fn lit(&mut self, n: i32) -> Result<(), String> {
        i16::try_from(n).map_err(|_| format!("{n}: literals are 16-bit"))?;
        if let Ok(b) = i8::try_from(n) {
            self.op("LIT8");
            self.code.push(b as u8);
        } else {
            // the stack's numbers are 32-bit; literals fit 16 (a frequency is never one)
            self.op("LIT16");
            self.code.extend((n as i16).to_le_bytes());
        }
        Ok(())
    }

    /// A string, a middle dot (U+00B7) as the one byte 0xB7 (the terminal prints it as a dot either way): a run
    /// reads a string a cache line at a time, so no character's bytes may be cut apart.
    fn str(&mut self, o: &str, s: &[u8]) -> Result<(), String> {
        let mut v = Vec::new();
        let mut i = 0;
        while i < s.len() {
            if s[i..].starts_with(&[0xC2, 0xB7]) {
                v.push(0xB7);
                i += 2;
            } else {
                v.push(s[i]);
                i += 1;
            }
        }
        self.op(o);
        self.code.push(u8::try_from(v.len()).map_err(|_| "a string over 255 bytes")?);
        self.code.extend(v);
        Ok(())
    }

    fn call(&mut self, w: &str) {
        self.op("CALL");
        self.calls.push((self.code.len(), w.into()));
        self.code.extend([0, 0]);
    }
}

/// What the source names: variables, natives, constants (pages and keys among them).
struct Names {
    vars: Vec<String>,
    locals: Vec<String>,
    nats: Vec<String>,
    /// Each native's stack effect: what it takes (low nibble) and gives (high).
    nat_io: Vec<u8>,
    consts: HashMap<String, i32>,
}

fn number(w: &str) -> Option<i32> {
    if let Some(h) = w.strip_prefix("0x") {
        return i32::from_str_radix(h, 16).ok();
    }
    if w.len() == 3 && w.starts_with('\'') && w.ends_with('\'') {
        return Some(w.as_bytes()[1] as i32);
    }
    w.parse().ok()
}

/// Compiles words and strings into `s`.
fn code(n: &Names, s: &mut Seg, t: &[T]) -> Result<(), String> {
    let mut i = 0;
    while i < t.len() {
        let w = match &t[i] {
            T::Str(x) => {
                s.str("STR", x)?;
                i += 1;
                continue;
            }
            T::W(w) => w.as_str(),
        };
        i += 1;
        let inline = |i: &mut usize| -> Result<Vec<u8>, String> {
            match t.get(*i) {
                Some(T::Str(x)) => {
                    *i += 1;
                    Ok(x.clone())
                }
                x => Err(format!("{w}: a string expected, got {x:?}")),
            }
        };
        if let Some((_, o)) = SIMPLE.iter().find(|(k, _)| *k == w) {
            s.op(o);
        } else if let Some(k) = w.strip_prefix("page_").and_then(|e| PAGE_ENTRIES.iter().position(|x| *x == e)) {
            s.op("PCALL");
            s.code.push(k as u8);
        } else if let Some(v) = w.strip_prefix('@').or_else(|| w.strip_prefix('!')).filter(|v| !v.is_empty()) {
            let k = n.vars.iter().chain(&n.locals).position(|x| x == v).ok_or_else(|| format!("no variable {v}"))?;
            s.op(if w.starts_with('@') { "GET" } else { "SET" });
            s.code.push(k as u8);
        } else if let Some(k) = n.nats.iter().position(|x| x == w) {
            s.op("NAT");
            s.code.extend([k as u8, n.nat_io[k]]);
        } else if let Some(&c) = n.consts.get(w) {
            s.lit(c)?;
        } else if let Some(c) = number(w) {
            s.lit(c)?;
        } else {
            match w {
                ".r" | ".z" => {
                    s.op("NUMW");
                    s.code.push(if w == ".r" { b' ' } else { b'0' });
                }
                "pick" => {
                    // piece i of "a|b|c": a chain of tests (nothing for i past the last)
                    let x = inline(&mut i)?;
                    let ps: Vec<&[u8]> = x.split(|c| *c == b'|').collect();
                    let mut v = Vec::new();
                    for (k, p) in ps.iter().enumerate() {
                        v.extend([crate::w("dup"), crate::w(&k.to_string()), crate::w("="), crate::w("if"), crate::w("drop")]);
                        if !p.is_empty() {
                            v.push(T::Str(p.to_vec()));
                        }
                        v.push(crate::w("else"));
                    }
                    v.push(crate::w("drop"));
                    v.extend(ps.iter().map(|_| crate::w("then")));
                    code(n, s, &v)?;
                }
                "raw" => s.str("RAW", &inline(&mut i)?)?,
                "bold" => {
                    let x = inline(&mut i)?;
                    s.call("bon");
                    s.str("STR", &x)?;
                    s.call("back");
                }
                "if" => {
                    s.op_a("JZ", 0);
                    s.ctl.push(('i', s.here() - 2));
                }
                "else" => {
                    let Some(('i', at)) = s.ctl.pop() else { return Err("else without if".into()) };
                    s.op_a("JMP", 0);
                    s.ctl.push(('i', s.here() - 2));
                    let h = s.here();
                    s.patch(at, h);
                }
                "then" => {
                    let Some(('i', at)) = s.ctl.pop() else { return Err("then without if".into()) };
                    let h = s.here();
                    s.patch(at, h);
                }
                "begin" => s.ctl.push(('b', s.here())),
                "while" => {
                    s.op_a("JZ", 0);
                    s.ctl.push(('w', s.here() - 2));
                }
                "repeat" => {
                    let Some(('w', at)) = s.ctl.pop() else { return Err("repeat without while".into()) };
                    let Some(('b', to)) = s.ctl.pop() else { return Err("repeat without begin".into()) };
                    s.op_a("JMP", to);
                    let h = s.here();
                    s.patch(at, h);
                }
                "until" => {
                    let Some(('b', to)) = s.ctl.pop() else { return Err("until without begin".into()) };
                    s.op_a("JZ", to);
                }
                _ => s.call(w),
            }
        }
    }
    Ok(())
}

/// A page's parts as written: its words' sources, rules, keys, hints and help.
#[derive(Default)]
struct PageSrc {
    name: String,
    hints: Vec<u8>,
    help: Vec<u8>,
    defs: Vec<(String, Vec<T>)>,
    pre: Vec<T>,
    rules: Vec<(String, i32, Option<T>, Vec<T>)>,
    keypre: Vec<T>,
    keys: Vec<(String, Vec<T>)>,
}

fn word(t: &[T], i: usize) -> Result<&str, String> {
    match t.get(i) {
        Some(T::W(w)) => Ok(w),
        x => Err(format!("a word expected, got {x:?}")),
    }
}

fn text(t: &[T], i: usize) -> Result<Vec<u8>, String> {
    match t.get(i) {
        Some(T::Str(s)) => Ok(s.clone()),
        x => Err(format!("a string expected, got {x:?}")),
    }
}

fn int(t: &[T], i: usize) -> Result<i32, String> {
    number(word(t, i)?).ok_or_else(|| format!("a number expected at {}", word(t, i).unwrap_or("")))
}

fn w(s: &str) -> T {
    T::W(s.into())
}

/// Hints ("Up/Dn=Move|Enter=Open") as the words that draw them: each key bold, then its meaning.
fn hints_code(h: &[u8]) -> Vec<T> {
    let mut v = Vec::new();
    for kl in h.split(|c| *c == b'|') {
        let mut p = kl.splitn(2, |c| *c == b'=');
        let k = p.next().unwrap_or_default();
        let l = p.next().unwrap_or_default();
        v.extend([w("bold"), T::Str(k.into())]);
        v.push(T::Str([&b" "[..], l, b"   "].concat()));
    }
    v
}

/// The help (lines cut at \n) as a word drawing body row `b`: the heading on row 1, the lines from row 3.
fn help_code(h: &[u8]) -> Vec<T> {
    let mut v = vec![w("dup"), w("1"), w("="), w("if"), w("drop"), T::Str(b" ".into()), w("bold"), T::Str(b"Help".into()), w("exit"), w("then"), w("3"), w("-")];
    for (k, l) in h.split(|c| *c == b'\n').enumerate() {
        v.extend([w("dup"), w(&k.to_string()), w("="), w("if"), w("drop"), T::Str([&b"  "[..], l].concat()), w("exit"), w("then")]);
    }
    v.push(w("drop"));
    v
}

/// A page's `draw`: its rules in order, the first that takes body row `b` draws it (`@i` the row in a list).
/// Each rule's body is a word of its own after it (`out`), so the tests run through a few cache lines and only the
/// row's body is read (TERM-47: the code is read from the part through a small cache).
fn draw_code(p: &PageSrc, out: &mut Vec<(String, Vec<T>)>) -> Vec<T> {
    let mut v = vec![w("!b"), w("0"), w("!end")];
    v.extend(p.pre.iter().cloned());
    for (kind, x, count, body) in &p.rules {
        let xs = x.to_string();
        let test: Vec<T> = match kind.as_str() {
            "row" => vec![w("@b"), w(&xs), w("=")],
            "bot" => vec![w("@b"), w("rows"), w("2"), w("-"), w(&xs), w("-"), w("=")],
            "tail" => vec![w("@b"), w("@end"), w(&xs), w("+"), w("=")],
            _ => {
                v.extend([w(&xs), count.clone().unwrap(), w("+"), w("!end")]);
                vec![w("@b"), w(&xs), w("<"), w("not"), w("@b"), w("@end"), w("<"), w("and"), w("if"), w("@b"), w(&xs), w("-"), w("!i"), w("1"), w("else"), w("0"), w("then")]
            }
        };
        v.extend(test);
        v.push(w("if"));
        v.push(out_of_line(body, "r", out));
        v.extend([w("exit"), w("then")]);
    }
    v
}

/// `body` as a word of its own in `out` (a call to it; a short one stays in place).
fn out_of_line(body: &[T], tag: &str, out: &mut Vec<(String, Vec<T>)>) -> T {
    let name = format!("_{tag}{}", out.len());
    out.push((name.clone(), body.to_vec()));
    w(&name)
}

/// A page's `key`: the code on the stack; each `key` line in order (a digit's line keeps the code for its words).
fn key_code(p: &PageSrc, out: &mut Vec<(String, Vec<T>)>) -> Result<Vec<T>, String> {
    let mut v = p.keypre.clone();
    let mut other = Vec::new();
    for (k, body) in &p.keys {
        if k == "else" {
            other = body.clone();
            continue;
        }
        if k == "digit" {
            v.extend([w("dup"), w("'1'"), w("<"), w("not"), w("over"), w("'9'"), w(">"), w("not"), w("and"), w("if")]);
        } else {
            let c = match KEYS.iter().find(|(n, _)| n == k) {
                Some((_, c)) => *c,
                None if k.len() == 1 => k.as_bytes()[0].to_ascii_lowercase() as i32,
                None => return Err(format!("no key {k}")),
            };
            v.extend([w("dup"), w(&c.to_string()), w("="), w("if"), w("drop")]);
        }
        v.push(out_of_line(body, "k", out));
        v.extend([w("exit"), w("then")]);
    }
    v.push(w("drop"));
    v.extend(other);
    Ok(v)
}

/// Places `defs` in `s` (a jump table for `entries` first), resolving calls against `known` and themselves.
fn assemble(n: &Names, s: &mut Seg, entries: &[&str], defs: &[(String, Vec<T>)], known: &HashMap<String, usize>) -> Result<HashMap<String, usize>, String> {
    let table = s.code.len();
    for _ in entries {
        s.op_a("JMP", 0);
    }
    let mut mine = HashMap::new();
    for (name, body) in defs {
        let builtin = SIMPLE.iter().any(|(k, _)| k == name) || n.nats.contains(name) || n.consts.contains_key(name);
        if builtin || ["if", "else", "then", "begin", "while", "repeat", "until", "pick", "raw", "bold", ".r", ".z"].contains(&name.as_str()) {
            return Err(format!("{name} is already a word of the language"));
        }
        if mine.insert(name.clone(), s.here()).is_some() {
            return Err(format!("{name} defined twice"));
        }
        code(n, s, body).map_err(|e| format!("in {name}: {e}"))?;
        if !s.ctl.is_empty() {
            return Err(format!("in {name}: an if or begin left open"));
        }
        s.op("RET");
    }
    for (k, e) in entries.iter().enumerate() {
        let a = *mine.get(*e).ok_or_else(|| format!("no word {e}"))?;
        let at = s.base + table + 3 * k + 1;
        s.patch(at, a);
    }
    for (at, name) in std::mem::take(&mut s.calls) {
        let a = mine.get(&name).or_else(|| known.get(&name)).ok_or_else(|| format!("no word {name}"))?;
        let at = s.base + at;
        s.patch(at, *a);
    }
    Ok(mine)
}

/// The pack, and every name's number for the firmware (name, Rust type, value).
type Compiled = (Vec<u8>, Vec<(String, &'static str, String)>);

fn compile(src: &str) -> Result<Compiled, String> {
    let mut n = Names { vars: Vec::new(), locals: Vec::new(), nats: Vec::new(), nat_io: Vec::new(), consts: HashMap::new() };
    for (k, c) in KEYS {
        n.consts.insert(format!("K_{}", k.to_uppercase()), c);
    }
    let mut lib: Vec<(String, Vec<T>)> = Vec::new();
    let mut pages: Vec<PageSrc> = Vec::new();
    let mut open: Option<(String, Vec<T>)> = None;
    let mut ids: Vec<(String, &'static str, String)> = Vec::new();
    let mut exports: Vec<String> = Vec::new();
    for (ln, line) in src.lines().enumerate() {
        let at = |e: String| format!("line {}: {e}", ln + 1);
        let tl = line.trim();
        if tl.is_empty() || tl.starts_with('#') {
            continue;
        }
        let mut t = tokens(tl).map_err(at)?;
        if t.first() == Some(&w(":")) {
            if open.is_some() {
                return Err(at("a definition inside a definition".into()));
            }
            open = Some((word(&t, 1).map_err(at)?.into(), Vec::new()));
            t.drain(..2);
        }
        if t.is_empty() {
            continue;
        }
        // a word's definition runs to its `;`
        if let Some((name, mut body)) = open.take() {
            let end = t.iter().position(|x| *x == w(";"));
            body.extend(t[..end.unwrap_or(t.len())].iter().cloned());
            match end {
                Some(e) if e + 1 < t.len() => return Err(at("something after ;".into())),
                Some(_) => match pages.last_mut() {
                    Some(p) => p.defs.push((name, body)),
                    None => lib.push((name, body)),
                },
                None => open = Some((name, body)),
            }
            continue;
        }
        let head = word(&t, 0).map_err(at)?;
        let rest = || t[1..].to_vec();
        let page = |pages: &mut Vec<PageSrc>| -> Result<usize, String> { pages.len().checked_sub(1).ok_or_else(|| at("outside a page".into())) };
        match head {
            "vars" | "locals" | "natives" | "export" => {
                let names: Result<Vec<String>, String> = t[1..].iter().map(|x| if let T::W(s) = x { Ok(s.clone()) } else { Err(at("names only".into())) }).collect();
                match head {
                    "vars" => {
                        if !n.locals.is_empty() {
                            return Err(at("vars before locals".into()));
                        }
                        n.vars.extend(names?)
                    }
                    "locals" => n.locals.extend(names?),
                    "natives" => {
                        let names = names?;
                        let io = (int(&t, 1).map_err(at)? | int(&t, 2).map_err(at)? << 4) as u8;
                        n.nat_io.extend(std::iter::repeat_n(io, names.len() - 2));
                        n.nats.extend(names[2..].iter().cloned());
                    }
                    _ => exports.extend(names?),
                }
            }
            "const" => {
                n.consts.insert(word(&t, 1).map_err(at)?.into(), int(&t, 2).map_err(at)?);
            }
            "hintsw" => lib.push((word(&t, 1).map_err(at)?.into(), hints_code(&text(&t, 2).map_err(at)?))),
            "page" => {
                let name = word(&t, 1).map_err(at)?.to_string();
                n.consts.insert(format!("P_{}", name.to_uppercase()), pages.len() as i32);
                pages.push(PageSrc { name, ..Default::default() });
            }
            "hints" => {
                let i = page(&mut pages)?;
                pages[i].hints = text(&t, 1).map_err(at)?;
            }
            "help" => {
                let i = page(&mut pages)?;
                pages[i].help = text(&t, 1).map_err(at)?;
            }
            "pre" => {
                let i = page(&mut pages)?;
                pages[i].pre.extend(rest());
            }
            "row" | "bot" | "tail" => {
                let i = page(&mut pages)?;
                pages[i].rules.push((head.into(), int(&t, 1).map_err(at)?, None, t[2..].to_vec()));
            }
            "list" => {
                let i = page(&mut pages)?;
                pages[i].rules.push((head.into(), int(&t, 1).map_err(at)?, Some(t[2].clone()), t[3..].to_vec()));
            }
            "key" => {
                let i = page(&mut pages)?;
                let k = match &t[1] {
                    T::Str(s) if s.len() == 1 => (s[0] as char).to_string(),
                    T::W(x) => x.clone(),
                    _ => return Err(at("a key".into())),
                };
                if k == "pre" {
                    pages[i].keypre.extend(t[2..].iter().cloned());
                } else {
                    pages[i].keys.push((k, t[2..].to_vec()));
                }
            }
            x => return Err(at(format!("unknown statement {x}"))),
        }
    }
    if open.is_some() {
        return Err("a definition without its ;".into());
    }
    // Layout: header, then the lib (its entries first), then each page (its entries first).
    let mut s = Seg { code: Vec::new(), base: 0, calls: Vec::new(), ctl: Vec::new() };
    let libw = assemble(&n, &mut s, &LIB_ENTRIES, &lib, &HashMap::new())?;
    let lib_code = s.code;
    let mut segs = Vec::new();
    for p in &pages {
        let mut defs = p.defs.clone();
        let have = |d: &Vec<(String, Vec<T>)>, e: &str| d.iter().any(|(x, _)| x == e);
        let mut bodies = Vec::new();
        if !have(&defs, "draw") {
            defs.push(("draw".into(), draw_code(p, &mut bodies)));
        }
        if !have(&defs, "key") {
            defs.push(("key".into(), key_code(p, &mut bodies).map_err(|e| format!("page {}: {e}", p.name))?));
        }
        defs.push(("hints".into(), hints_code(&p.hints)));
        for e in ["help", "prep", "poll"] {
            if !have(&defs, e) {
                defs.push((e.into(), Vec::new()));
            }
        }
        defs.extend(bodies);
        let mut s = Seg { code: Vec::new(), base: lib_code.len(), calls: Vec::new(), ctl: Vec::new() };
        let pw = assemble(&n, &mut s, &PAGE_ENTRIES, &defs, &libw).map_err(|e| format!("page {}: {e}", p.name))?;
        for x in &exports {
            if let Some(a) = pw.get(x) {
                ids.push((format!("W_{}_{}", p.name.to_uppercase(), x.to_uppercase()), "usize", a.to_string()));
            }
        }
        s.code.extend([0, 0]); // the interpreter reads an opcode's two bytes after it
        segs.push(s.code);
    }
    // Each page's help in a segment of its own, read instead of the page while the help shows (its other
    // entries do nothing).
    for p in &pages {
        let mut defs: Vec<(String, Vec<T>)> = PAGE_ENTRIES.iter().map(|e| (e.to_string(), Vec::new())).collect();
        defs[3].1 = help_code(&p.help);
        let mut s = Seg { code: Vec::new(), base: lib_code.len(), calls: Vec::new(), ctl: Vec::new() };
        assemble(&n, &mut s, &PAGE_ENTRIES, &defs, &libw).map_err(|e| format!("page {} help: {e}", p.name))?;
        s.code.extend([0, 0]);
        segs.push(s.code);
    }
    let ns = segs.len();
    let mut o = Vec::new();
    o.extend(b"FVT\x02");
    o.push(ns as u8);
    o.push(0);
    o.extend((lib_code.len() as u16).to_le_bytes());
    let mut at = 8 + 4 * ns + lib_code.len();
    for sg in &segs {
        o.extend((at as u16).to_le_bytes());
        o.extend((sg.len() as u16).to_le_bytes());
        at += sg.len();
    }
    o.extend(&lib_code);
    for sg in &segs {
        o.extend(sg);
    }
    let most = segs.iter().map(|s| s.len()).max().unwrap_or(0) + lib_code.len();
    if most > 0xFFFF {
        return Err(format!("the lib and a page take {most} bytes: code addresses are 16-bit"));
    }
    ids.push(("NPAGES".into(), "i16", pages.len().to_string()));
    for (k, o) in OPS.iter().enumerate() {
        ids.push((format!("OP_{o}"), "u8", k.to_string()));
    }
    for (k, v) in n.vars.iter().chain(&n.locals).enumerate() {
        ids.push((format!("V_{}", v.to_uppercase()), "usize", k.to_string()));
    }
    ids.push(("NV".into(), "usize", n.vars.len().to_string()));
    ids.push(("NL".into(), "usize", n.locals.len().to_string()));
    for (k, v) in n.nats.iter().enumerate() {
        ids.push((format!("N_{}", v.to_uppercase()), "u8", k.to_string()));
    }
    let mut cs: Vec<_> = n.consts.iter().collect();
    cs.sort();
    for (k, v) in cs {
        ids.push((format!("C_{}", k.to_uppercase()), "i32", v.to_string()));
    }
    for (k, e) in LIB_ENTRIES.iter().enumerate() {
        ids.push((format!("E_{}", e.to_uppercase()), "usize", (3 * k).to_string()));
    }
    for x in &exports {
        if let Some(a) = libw.get(x) {
            ids.push((format!("W_{}", x.to_uppercase()), "usize", a.to_string()));
        }
    }
    Ok((o, ids))
}

// ---- the text pack ----

/// A `txt!`/`txtc!` literal: its source text between the quotes (what the macro arm matches) and its value.
struct Lit {
    raw: String,
    value: Vec<u8>,
}

/// The string literal starting at `b[i]` (a `"`): its raw text and value, and where it ends.
fn literal(b: &[u8], i: usize) -> Result<(Lit, usize), String> {
    let mut j = i + 1;
    let mut v = Vec::new();
    while j < b.len() && b[j] != b'"' {
        if b[j] == b'\\' {
            j += 1;
            match b[j] {
                b'n' => v.push(b'\n'),
                b't' => v.push(b'\t'),
                b'r' => v.push(b'\r'),
                b'0' => v.push(0),
                b'\\' | b'"' | b'\'' => v.push(b[j]),
                b'x' => {
                    v.push(u8::from_str_radix(std::str::from_utf8(&b[j + 1..j + 3]).unwrap(), 16).map_err(|e| e.to_string())?);
                    j += 2;
                }
                b'u' => {
                    let end = j + b[j..].iter().position(|&c| c == b'}').ok_or("no } in \\u{}")?;
                    let h = std::str::from_utf8(&b[j + 2..end]).unwrap();
                    let c = char::from_u32(u32::from_str_radix(h, 16).map_err(|e| e.to_string())?).ok_or("bad \\u")?;
                    let mut t = [0u8; 4];
                    v.extend_from_slice(c.encode_utf8(&mut t).as_bytes());
                    j = end;
                }
                b'\n' => {
                    while j + 1 < b.len() && b[j + 1].is_ascii_whitespace() {
                        j += 1;
                    }
                }
                c => return Err(format!("unknown escape \\{}", c as char)),
            }
            j += 1;
        } else {
            v.push(b[j]);
            j += 1;
        }
    }
    if j >= b.len() {
        return Err("no closing quote".into());
    }
    Ok((Lit { raw: String::from_utf8(b[i + 1..j].to_vec()).unwrap(), value: v }, j + 1))
}

fn rs_files(dir: &std::path::Path, out: &mut Vec<std::path::PathBuf>) {
    let mut v: Vec<_> = std::fs::read_dir(dir).unwrap().map(|e| e.unwrap().path()).collect();
    v.sort();
    for p in v {
        if p.is_dir() {
            rs_files(&p, out);
        } else if p.extension().is_some_and(|e| e == "rs") {
            out.push(p);
        }
    }
}

/// The text pack: every literal of `txt!(` and `txtc!(` in `src/`, in file order, each once.
fn texts() {
    println!("cargo:rerun-if-changed=src");
    let mut files = Vec::new();
    rs_files(std::path::Path::new("src"), &mut files);
    let mut lits: Vec<Lit> = Vec::new();
    for f in &files {
        let src = std::fs::read_to_string(f).unwrap();
        let b = src.as_bytes();
        let mut i = 0;
        // The terminal's refusals, `no!(t, "...", ...)` (term/cmd.rs), go through `txt!` too.
        let mut k = 0;
        while let Some(p) = src[k..].find("no!(") {
            let at = k + p;
            k = at + 4;
            let line_start = src[..at].rfind('\n').map_or(0, |n| n + 1);
            if src[line_start..at].contains("//") || at > 0 && (b[at - 1].is_ascii_alphanumeric() || b[at - 1] == b'_') {
                continue;
            }
            // the first argument (an expression without quotes), a comma, then the literal
            let Some(q) = src[k..].find(['"', ')', ';']) else { continue };
            if b[k + q] != b'"' || !src[k..k + q].contains(',') {
                continue;
            }
            let (lit, _) = literal(b, k + q).unwrap_or_else(|e| panic!("{}: {e}", f.display()));
            if lit.value.len() > 255 {
                panic!("{}: a text of {} bytes (255 at most: split it): {}", f.display(), lit.value.len(), lit.raw);
            }
            if !lits.iter().any(|l| l.raw == lit.raw) {
                lits.push(lit);
            }
        }
        while let Some(p) = src[i..].find("txt") {
            let at = i + p;
            i = at + 3;
            let rest = &src[at..];
            let skip = if rest.starts_with("txt!(") {
                5
            } else if rest.starts_with("txtc!(") {
                6
            } else {
                continue;
            };
            // not in a comment, nor part of a longer name
            let line_start = src[..at].rfind('\n').map_or(0, |n| n + 1);
            if src[line_start..at].contains("//") || at > 0 && (b[at - 1].is_ascii_alphanumeric() || b[at - 1] == b'_') {
                continue;
            }
            let mut j = at + skip;
            while b[j].is_ascii_whitespace() {
                j += 1;
            }
            if b[j] != b'"' {
                continue; // the macro's own definition (`$t`)
            }
            let (lit, end) = literal(b, j).unwrap_or_else(|e| panic!("{}: {e}", f.display()));
            if lit.value.len() > 255 {
                panic!("{}: a text of {} bytes (255 at most: split it): {}", f.display(), lit.value.len(), lit.raw);
            }
            if !lits.iter().any(|l| l.raw == lit.raw) {
                lits.push(lit);
            }
            i = end;
        }
    }
    assert!(lits.len() < 31 << 6, "too many texts for txtc!'s two characters");
    // The body: count u16, 0 u16, an entry per text (offset from the body's start, length in the top 8 bits), texts.
    let n = lits.len();
    let mut body = Vec::new();
    body.extend_from_slice(&(n as u16).to_le_bytes());
    body.extend_from_slice(&[0, 0]);
    let mut at = 4 + 4 * n;
    for l in &lits {
        body.extend_from_slice(&((at as u32) | (l.value.len() as u32) << 24).to_le_bytes());
        at += l.value.len();
    }
    for l in &lits {
        body.extend_from_slice(&l.value);
    }
    let mut rs = String::from("// Generated by build.rs from the txt!/txtc! literals in src/ (the text pack).\n");
    rs.push_str("/// A text in the text pack, by its literal: its number (UPD-22).\n#[allow(unused_macros)]\nmacro_rules! txt {\n");
    for (k, l) in lits.iter().enumerate() {
        writeln!(rs, "    (\"{}\") => {{ $crate::text::Txt({k}) }};", l.raw).unwrap();
    }
    rs.push_str("    ($t:tt) => { compile_error!(\"txt!: a string literal\") };\n");
    rs.push_str("}\n/// A text's number as two characters, for a table string (`concat!`): `text::code`.\n#[allow(unused_macros)]\nmacro_rules! txtc {\n");
    for (k, l) in lits.iter().enumerate() {
        // a control character, then one of 0x20-0x5F: never a `|`, so a table string's fields still split
        writeln!(rs, "    (\"{}\") => {{ \"\\u{{{:x}}}\\u{{{:x}}}\" }};", l.raw, 1 + (k >> 6), 0x20 + (k & 0x3F)).unwrap();
    }
    rs.push_str("    ($t:tt) => { compile_error!(\"txtc!: a string literal\") };\n}\n");
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out.join("txt_macros.rs"), rs).unwrap();
    std::fs::write(out.join("text_en.bin"), body).unwrap();
}
